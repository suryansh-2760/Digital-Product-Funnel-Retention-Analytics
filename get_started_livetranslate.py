def generate_events(n_users=20000, n_days=120, start="2025-01-01", seed=SEED):
    """
    Documented synthetic event log. Columns:
      event_id     unique id of the emitted row (retries re-emit the SAME id)
      anon_id      cookie / device id (a user on 2 devices has 2 anon_ids)
      user_id      account id, only present after login (else None)
      event_name   one of STAGES
      ts           event timestamp
      device, source (source = utm source on the event; 'direct' on some return visits)
      true_user    ground-truth user (synthetic only; used to audit identity stitching)

    Built-in data problems to detect / fix:
      * 3% exact duplicate rows (same event_id)         -> retry/double-send
      * 2% near duplicates (new id, <1.5s later)        -> double-fired tags
      * 1% of late-funnel events with skewed timestamps -> ordering violations
      * 0.2% missing timestamps
      * login happens mid-journey -> anon events must be stitched to user_id
      * 15% of users use a 2nd device (a second anon_id)
    Built-in structure (so findings are non-trivial):
      * mobile has checkout friction; social traffic skews mobile (confounding!)
      * email has high intent and revisit rate
    """
    rng = np.random.default_rng(seed)
    base = pd.Timestamp(start)
    src_names = ["organic", "paid_search", "social", "email", "referral"]
    src_p = [.35, .25, .20, .10, .10]
    src_intent = {"organic": 1.0, "paid_search": .9, "social": .7, "email": 1.35, "referral": 1.1}
    src_revisit = {"organic": 1.0, "paid_search": .7, "social": .8, "email": 2.0, "referral": 1.2}
    dev_names = np.array(["mobile", "desktop", "tablet"])
    dev_given_src = {"organic": [.50, .43, .07], "paid_search": [.50, .43, .07],
                     "social": [.80, .15, .05], "email": [.55, .38, .07],
                     "referral": [.45, .48, .07]}
    dev_checkout = {"mobile": .78, "desktop": 1.1, "tablet": 1.0}

    src = rng.choice(src_names, n_users, p=src_p)
    dev = np.empty(n_users, dtype=object)
    for s in src_names:
        m = src == s
        dev[m] = rng.choice(dev_names, m.sum(), p=dev_given_src[s])
    first_day = rng.integers(0, n_days - 14, n_users)
    revisit = np.array([src_revisit[s] for s in src])
    n_sess = np.minimum(1 + rng.poisson(0.9 * revisit), 12)

    # ---- sessions
    uid = np.repeat(np.arange(n_users), n_sess)
    k = np.arange(len(uid)) - np.repeat(np.cumsum(n_sess) - n_sess, n_sess)
    gap_days = np.where(k == 0, 0.0, rng.exponential(6.0, len(uid)))
    cum = pd.Series(gap_days).groupby(uid).cumsum().to_numpy()
    start_sec = (first_day[uid] + cum) * 86400 + rng.integers(7 * 3600, 23 * 3600, len(uid))
    keep = start_sec < n_days * 86400
    uid, k, start_sec = uid[keep], k[keep], start_sec[keep]
    n = len(uid)

    has2 = rng.random(n_users) < .15
    switch = has2[uid] & (k >= 1) & (rng.random(n) < .5)
    alt_dev = np.where(dev == "mobile", "desktop", "mobile")
    s_dev = np.where(switch, alt_dev[uid], dev[uid])
    anon = np.array([f"a{u}_{1 + int(sw)}" for u, sw in zip(uid, switch)])
    s_src = np.where(k == 0, src[uid],
                     np.where(rng.random(n) < .5, "direct", src[uid]))

    # ---- funnel progression per session
    intent = np.array([src_intent[s] for s in src[uid]]) ** .6 * np.where(k > 0, 1.1, 1.0)
    dco = np.array([dev_checkout[d] for d in s_dev])
    p = [np.clip(.62 * intent, 0, .97), np.clip(.34 * intent, 0, .97),
         np.clip(.55 * intent * dco, 0, .97), np.clip(.60 * intent * dco, 0, .97)]
    reach = [np.ones(n, bool)]
    for j in range(4):
        reach.append(reach[-1] & (rng.random(n) < p[j]))
    t = [start_sec.astype(float)]
    t.append(t[0] + 10 + rng.exponential(60, n))
    t.append(t[1] + 15 + rng.exponential(120, n))
    t.append(t[2] + 20 + rng.exponential(300, n))
    t.append(t[3] + 30 + rng.exponential(600, n))       # long tail -> session-gap sensitivity

    # ---- login: ~60% of users log in at a random session; checkout/purchase require login
    login_k = np.where(rng.random(n_users) < .6, rng.integers(0, 3, n_users), 99)

    parts = []
    for j, name in enumerate(STAGES):
        m = reach[j]
        logged = (k[m] > login_k[uid[m]]) | ((k[m] == login_k[uid[m]]) & (j >= 1)) | (j >= 3)
        parts.append(pd.DataFrame({
            "anon_id": anon[m],
            "user_id": np.where(logged, np.char.add("u", uid[m].astype(str)), None),
            "true_user": uid[m],
            "event_name": name,
            "stage": j,
            "ts_sec": t[j][m],
            "device": s_dev[m],
            "source": s_src[m]}))
    ev = pd.concat(parts, ignore_index=True)
    ev["ts"] = base + pd.to_timedelta(ev.pop("ts_sec"), unit="s")
    ev["event_id"] = np.arange(len(ev))
    N = len(ev)

    # ---- inject data-quality problems
    skew = (ev.stage.to_numpy() >= 2) & (rng.random(N) < .01)
    ev.loc[skew, "ts"] -= pd.to_timedelta(rng.uniform(600, 7200, skew.sum()), unit="s")
    dup_exact = ev.sample(frac=.03, random_state=seed)
    near = ev.sample(frac=.02, random_state=seed + 1).copy()
    near["event_id"] = np.arange(N, N + len(near))
    near["ts"] += pd.to_timedelta(rng.uniform(.1, 1.5, len(near)), unit="s")
    ev = pd.concat([ev, dup_exact, near], ignore_index=True)
    ev.loc[rng.random(len(ev)) < .002, "ts"] = pd.NaT
    ev = ev.drop(columns="stage").sample(frac=1, random_state=seed).reset_index(drop=True)
    return ev[["event_id", "anon_id", "user_id", "event_name", "ts", "device", "source", "true_user"]]


