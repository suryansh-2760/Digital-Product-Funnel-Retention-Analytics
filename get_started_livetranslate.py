def stitch_identity(df):
    """person_id = user_id if present, else the user_id this anon_id was later seen with,
    else the anon_id itself. Returns (df, stats)."""
    pairs = df.dropna(subset=["user_id"])[["anon_id", "user_id"]].drop_duplicates()
    conflicts = int((pairs.groupby("anon_id")["user_id"].nunique() > 1).sum())
    amap = pairs.drop_duplicates("anon_id").set_index("anon_id")["user_id"]
    df = df.copy()
    df["person_id"] = df["user_id"].fillna(df["anon_id"].map(amap)).fillna(df["anon_id"])
    return df, {"anon_ids_linked_to_multiple_users": conflicts,
                "anon_ids_stitched_to_a_user": int(len(amap))}


def clean_events(raw, near_dup_sec=2.0):
    """
    EVENT GRAIN: one row = one (person_id, event_name, timestamp) occurrence.
    Dedupe in two passes:
      a) same event_id  -> retried delivery of the identical row
      b) same person + event_name within `near_dup_sec` seconds -> double-fired tag
    """
    log = {"raw_rows": len(raw)}
    df = raw.copy()
    df["ts"] = pd.to_datetime(df["ts"], errors="coerce")
    log["null_timestamp_rows_dropped"] = int(df.ts.isna().sum())
    df = df.dropna(subset=["ts"])
    n0 = len(df)
    df = df.drop_duplicates("event_id")
    log["exact_duplicates_removed"] = n0 - len(df)
    df, stitch_stats = stitch_identity(df)
    log.update(stitch_stats)
    df = df.sort_values(["person_id", "event_name", "ts"])
    gap = df.groupby(["person_id", "event_name"])["ts"].diff().dt.total_seconds()
    near = (gap < near_dup_sec).to_numpy()
    log["near_duplicates_removed"] = int(near.sum())
    df = df[~near].sort_values(["person_id", "ts"]).reset_index(drop=True)
    log["clean_rows"] = len(df)
    return df, log


def sessionize(df, gap_min=SESSION_GAP_MIN):
    """New session when the gap to the person's previous event exceeds gap_min minutes."""
    df = df.sort_values(["person_id", "ts"]).copy()
    gap = df.groupby("person_id")["ts"].diff()
    new = gap.isna() | (gap > pd.Timedelta(minutes=gap_min))
    df["session_id"] = new.cumsum().to_numpy()
    df["session_no"] = new.astype(int).groupby(df["person_id"]).cumsum().to_numpy()
    return df


def validate_events(df, log):
    """Identity, ordering and session sanity checks -> DataFrame of (check, value)."""
    rows = [(k, v) for k, v in log.items()]
    first = df[df.event_name.isin(STAGES)].groupby(["person_id", "event_name"])["ts"].min().unstack()
    rows.append(("persons", df.person_id.nunique()))
    rows.append(("sessions", df.session_id.nunique()))
    rows.append(("share_events_with_user_id", df.user_id.notna().mean()))
    if "true_user" in df:
        rows.append(("identity_fragmentation (persons per true user; 1.0 ideal)",
                     df.person_id.nunique() / df.true_user.nunique()))
        rows.append(("share_persons_mixing_>1_true_user (should be 0)",
                     (df.groupby("person_id")["true_user"].nunique() > 1).mean()))
    for a, b in zip(STAGES[:-1], STAGES[1:]):
        both = first[[a, b]].dropna()
        rows.append((f"order_violation {b} before {a}", (both[b] < both[a]).mean()))
    rows.append(("purchase_without_checkout_start_persons",
                 int((first["purchase"].notna() & first["checkout_start"].isna()).sum())))
    rows.append(("sessions_spanning_>1_device_share",
                 (df.groupby("session_id")["device"].nunique() > 1).mean()))
    dur = df.groupby("session_id")["ts"].agg(lambda s: (s.max() - s.min()).total_seconds() / 60)
    rows.append(("session_duration_min_median", dur.median()))
    rows.append(("session_duration_min_p95", dur.quantile(.95)))
    return pd.DataFrame(rows, columns=["check", "value"])


def person_attributes(df):
    """First-touch attributes per person + acquisition cohort."""
    d = df.sort_values("ts")
    a = d.groupby("person_id").agg(first_ts=("ts", "min"), device=("device", "first"))
    s = d[d.source != "direct"].groupby("person_id")["source"].first()
    a["source"] = s.reindex(a.index).fillna("direct")
    a["cohort_week"] = a.first_ts.dt.normalize() - pd.to_timedelta(a.first_ts.dt.weekday, unit="D")
    a["cohort_month"] = a.first_ts.dt.to_period("M").astype(str)
    return a


