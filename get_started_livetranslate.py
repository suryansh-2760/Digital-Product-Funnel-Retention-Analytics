def weekly_activity(df, attrs):
    """Unique (person, weeks-since-first-seen) activity rows."""
    d = df[["person_id", "ts"]].join(attrs["first_ts"], on="person_id")
    d["k"] = (d.ts - d.first_ts).dt.days // 7
    return d.drop_duplicates(["person_id", "k"])[["person_id", "k"]]


def retention_curve(act, attrs, last_ts, col=None, K=8, min_n=50):
    """Share of persons active in week k after first seen, counting only persons whose
    week k is fully observed (handles right-censoring). Returns DataFrame (k x group)."""
    groups = [("all", attrs)] if col is None else [(g, a) for g, a in attrs.groupby(col)]
    out = {}
    for name, a in groups:
        r = []
        for k in range(K + 1):
            obs = a.index[(a.first_ts + pd.Timedelta(days=7 * (k + 1))) <= last_ts]
            if len(obs) < min_n:
                r.append(np.nan)
                continue
            active = act.loc[(act.k == k) & act.person_id.isin(obs), "person_id"].nunique()
            r.append(active / len(obs))
        out[name] = r
    return pd.DataFrame(out, index=range(K + 1))


def repeat_engagement(df, attrs, by="source"):
    d = df.assign(is_p=df.event_name.eq("purchase"))
    p = d.groupby("person_id").agg(sessions=("session_id", "nunique"), purchases=("is_p", "sum"))
    st = d.groupby(["person_id", "session_id"])["ts"].min().reset_index().sort_values(["person_id", "ts"])
    st["n"] = st.groupby("person_id").cumcount()
    s1 = st[st.n == 0].set_index("person_id")["ts"]
    s2 = st[st.n == 1].set_index("person_id")["ts"]
    p["days_to_2nd_session"] = (s2 - s1).dt.total_seconds() / 86400
    p = p.join(attrs[[by]])

    def summ(g):
        buyers = g[g.purchases >= 1]
        return pd.Series({
            "persons": len(g),
            "mean_sessions": g.sessions.mean(),
            "pct_2plus_sessions": (g.sessions >= 2).mean(),
            "median_days_to_2nd_session": g.days_to_2nd_session.median(),
            "pct_buyers": len(buyers) / len(g),
            "pct_repeat_buyers_of_buyers": (buyers.purchases >= 2).mean() if len(buyers) else np.nan})
    tab = pd.concat([summ(p).rename("ALL")] + [summ(g).rename(n) for n, g in p.groupby(by)], axis=1).T
    return tab, p


