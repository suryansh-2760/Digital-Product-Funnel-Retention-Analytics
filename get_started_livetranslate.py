def n_per_arm(p, rel_lift, alpha_z=1.96, power_z=0.84):
    """Two-proportion sample size per arm (normal approximation, 5% two-sided, 80% power)."""
    return int(np.ceil(2 * (alpha_z + power_z) ** 2 * p * (1 - p) / (p * rel_lift) ** 2))


