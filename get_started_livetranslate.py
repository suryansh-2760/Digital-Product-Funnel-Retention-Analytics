def load_real_events(path, colmap, event_map):
    """
    Map a real event CSV to the schema used above, e.g. RetailRocket:
      colmap   = {"timestamp": "ts", "visitorid": "anon_id", "event": "event_name"}
      event_map= {"view": "product_view", "addtocart": "add_to_cart", "transaction": "purchase"}
    then call main(raw=...) with STAGES edited to the stages that exist
    (no checkout_start there -> STAGES = ["product_view","add_to_cart","purchase"]).
    Missing columns (device, source, user_id) are filled with 'unknown' / None.
    """
    d = pd.read_csv(path).rename(columns=colmap)
    d["event_name"] = d["event_name"].map(event_map)
    d = d.dropna(subset=["event_name"])
    if np.issubdtype(d["ts"].dtype, np.number):
        d["ts"] = pd.to_datetime(d["ts"], unit="ms")
    for c, v in [("device", "unknown"), ("source", "unknown"), ("user_id", None)]:
        if c not in d:
            d[c] = v
    d["event_id"] = np.arange(len(d))
    return d[["event_id", "anon_id", "user_id", "event_name", "ts", "device", "source"]]


