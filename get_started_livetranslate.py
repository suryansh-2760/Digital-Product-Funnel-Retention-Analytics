def segment_funnels(reached, attrs, cols=("device", "source", "cohort_month"), n_boot=N_BOOT, rng=None):
    rng = rng or np.random.default_rng(SEED)
    a = attrs.loc[reached.index]
    arr = reached.to_numpy()
    y = reached[STAGES[-1]].to_numpy().astype(float)
    rows, comps = [], []
    for col in cols:
        for lvl in sorted(a[col].unique()):
            m = (a[col] == lvl).to_numpy()
            if m.sum() < 200:
                continue
            c = arr[m].sum(axis=0)
            ci = np.percentile(boot_means(y[m], n_boot, rng), [2.5, 97.5])
            rows.append({"segment": col, "level": lvl, "persons": int(m.sum()),
                         **{f"{s}": c[i] / c[0] for i, s in enumerate(STAGES)},
                         **{f"step_{s}": (c[i] / c[i - 1] if i else np.nan) for i, s in enumerate(STAGES)},
                         "purchase_lo": ci[0], "purchase_hi": ci[1]})
            d, lo, hi, p = compare_to_rest(y, m, n_boot, rng)
            comps.append({"segment": col, "level": lvl, "purchase_conv": y[m].mean(),
                          "diff_vs_rest": d, "diff_lo": lo, "diff_hi": hi, "p_boot": p})
    return pd.DataFrame(rows), pd.DataFrame(comps)


def device_gap_adjusted(y, dev, src, a="mobile", b="desktop", n_boot=500, rng=None):
    """Raw vs source-standardised conversion gap between two devices (observational
    confounding check: social traffic skews mobile). Bootstrap CIs."""
    rng = rng or np.random.default_rng(SEED)
    dev = np.asarray(dev)
    keep = (dev == a) | (dev == b)
    y, dev = y[keep].astype(float), dev[keep]
    sc, levels = pd.factorize(np.asarray(src)[keep])
    S = len(levels)

    def stat(y, dev, sc):
        w = np.bincount(sc, minlength=S) / len(sc)
        rates = []
        for lvl in (a, b):
            m = dev == lvl
            num = np.bincount(sc[m], weights=y[m], minlength=S)
            den = np.bincount(sc[m], minlength=S)
            rates.append(np.divide(num, den, out=np.zeros(S), where=den > 0))
        return y[dev == a].mean() - y[dev == b].mean(), ((rates[0] - rates[1]) * w).sum()

    raw, adj = stat(y, dev, sc)
    boots = np.array([stat(y[i], dev[i], sc[i]) for i in
                      (rng.integers(0, len(y), len(y)) for _ in range(n_boot))])
    r_ci, a_ci = np.percentile(boots[:, 0], [2.5, 97.5]), np.percentile(boots[:, 1], [2.5, 97.5])
    tbl = (pd.DataFrame({"y": y, "device": dev, "source": np.asarray(src)[keep]})
           .pivot_table(index="source", columns="device", values="y", aggfunc="mean"))
    return {"raw_gap": raw, "raw_ci": r_ci, "adj_gap": adj, "adj_ci": a_ci, "table": tbl}


