# 4. NUMPY BOOTSTRAP
# ----------------------------------------------------------------------------
def boot_counts(arr, n_boot, rng):
    """Resample units with replacement; return (n_boot, n_stages) reached-counts."""
    n, k = arr.shape
    out = np.empty((n_boot, k))
    chunk = max(1, int(2_000_000 // n))
    for i in range(0, n_boot, chunk):
        m = min(chunk, n_boot - i)
        idx = rng.integers(0, n, size=(m, n))
        out[i:i + m] = arr[idx].sum(axis=1)
    return out


def boot_means(y, n_boot, rng):
    n = len(y)
    out = np.empty(n_boot)
    chunk = max(1, int(2_000_000 // n))
    for i in range(0, n_boot, chunk):
        m = min(chunk, n_boot - i)
        out[i:i + m] = y[rng.integers(0, n, size=(m, n))].mean(axis=1)
    return out


def funnel_table(reached, n_boot=N_BOOT, rng=None):
    """Funnel counts with 95% bootstrap CIs for step and overall conversion."""
    rng = rng or np.random.default_rng(SEED)
    tab = funnel_counts(reached)
    c = boot_counts(reached.to_numpy(), n_boot, rng)
    overall = c / c[:, [0]]
    step = np.full_like(c, np.nan)
    step[:, 1:] = c[:, 1:] / np.maximum(c[:, :-1], 1)
    tab["overall_lo"], tab["overall_hi"] = np.percentile(overall, [2.5, 97.5], axis=0)
    tab["step_lo"], tab["step_hi"] = np.nan, np.nan
    tab.iloc[1:, tab.columns.get_loc("step_lo")] = np.percentile(step[:, 1:], 2.5, axis=0)
    tab.iloc[1:, tab.columns.get_loc("step_hi")] = np.percentile(step[:, 1:], 97.5, axis=0)
    return tab


def compare_to_rest(y, mask, n_boot, rng):
    """Difference in conversion (segment - everyone else), bootstrap 95% CI and p-value."""
    a, b = y[mask], y[~mask]
    d = boot_means(a, n_boot, rng) - boot_means(b, n_boot, rng)
    p = 2 * min((d <= 0).mean(), (d >= 0).mean())
    return a.mean() - b.mean(), *np.percentile(d, [2.5, 97.5]), max(p, 1 / n_boot)


