def ordered_funnel(df, key, stages=STAGES, window=None, ordered=True):
    """
    Boolean matrix (rows = key, cols = stages): did the unit reach each stage?
      key     ['person_id'] (user-level) or ['session_id'] (session-level)
      ordered stage k must occur at/after the time stage k-1 was reached
      window  stage k must occur within `window` of the entry (first page_view)
    The funnel is nested: reaching stage k requires reaching k-1.
    """
    ev = df[df.event_name.isin(stages)][key + ["event_name", "ts"]]
    entry = ev[ev.event_name == stages[0]].groupby(key)["ts"].min()
    entry.name = "t0"
    cols, prev = {stages[0]: entry}, entry
    entry_df = entry.reset_index()
    for s in stages[1:]:
        e = (ev[ev.event_name == s]
             .merge(prev.rename("prev").reset_index(), on=key)
             .merge(entry_df, on=key))
        if ordered:
            e = e[e.ts >= e.prev]
        if window is not None:
            e = e[e.ts <= e.t0 + window]
        t = e.groupby(key)["ts"].min()
        cols[s] = t
        prev = t
    return pd.DataFrame(cols).notna()


def funnel_counts(reached):
    c = reached.sum()
    return pd.DataFrame({"users": c, "step_conv": c / c.shift(1), "overall_conv": c / c.iloc[0]})


