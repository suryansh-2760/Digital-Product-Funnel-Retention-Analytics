def session_gap_sensitivity(df, eligible, gaps=(10, 30, 60, 120)):
    rows = []
    for g in gaps:
        s = sessionize(df, g)
        s = s[s.person_id.isin(eligible)]
        r = ordered_funnel(s, ["session_id"])
        rows.append({"gap_min": g, "sessions": s.session_id.nunique(),
                     "sessions_per_person": s.session_id.nunique() / s.person_id.nunique(),
                     "session_pv_to_purchase": r["purchase"].mean(),
                     "session_pv_to_checkout": r["checkout_start"].mean()})
    return pd.DataFrame(rows)


def definition_sensitivity(df_sess, eligible, n_boot=500, rng=None):
    rng = rng or np.random.default_rng(SEED)
    d = df_sess[df_sess.person_id.isin(eligible)]
    defs = [
        ("User | strict order | 7d window", ["person_id"], dict(window=pd.Timedelta(days=7))),
        ("User | strict order | 24h window", ["person_id"], dict(window=pd.Timedelta(days=1))),
        ("User | strict order | no window", ["person_id"], dict()),
        ("User | any order | 7d window", ["person_id"], dict(window=pd.Timedelta(days=7), ordered=False)),
        (f"Session ({SESSION_GAP_MIN}m) | strict order", ["session_id"], dict()),
    ]
    rows = []
    for name, key, kw in defs:
        r = ordered_funnel(d, key, **kw)
        y = r["purchase"].to_numpy().astype(float)
        lo, hi = np.percentile(boot_means(y, n_boot, rng), [2.5, 97.5])
        rows.append({"definition": name, "entrants": len(r), "purchase_conv": y.mean(),
                     "lo": lo, "hi": hi, "cart_to_purchase": r["purchase"].sum() / max(r["add_to_cart"].sum(), 1)})
    return pd.DataFrame(rows)


